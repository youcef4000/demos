/** « 3 leçons », « 40 lessons », « 40 درسًا » : nombre + nom accordé dans la langue de l'interface. */
export function plural(word, n) {
  const forms = PL[lang]?.[word] || PL.fr[word];
  const s = forms[RULES.select(n)] ?? forms.other;
  return s.replace('{n}', fmtNum(n));
}

