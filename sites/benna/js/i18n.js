export const dir = () => (lang() === 'ar' ? 'rtl' : 'ltr');

export function t(cle, valeurs) {
  const ligne = T[cle];
  let texte = ligne ? ligne[ORDRE[lang()]] : cle;
  if (valeurs) for (const [k, v] of Object.entries(valeurs)) texte = texte.replaceAll(`{${k}}`, v);
  return texte;
}

// Texte d'un objet { fr, ar, en } dans la langue courante.
export const tl = (o) => (o ? o[lang()] ?? o.fr ?? '' : '');

export const CLES = Object.keys(T);
